// Command gen compiles the glass's shaders ahead of time, so that
// renderers start without compiling them: the Metal library on macOS,
// with Xcode's metal tools, into shaders_darwin.go, and the Direct3D
// bytecode on Windows, with the system's d3dcompiler_47.dll, into
// shaders_windows.go. Run it on each: go generate ./plugins/glass
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"runtime"

	"github.com/egoist/mygo/internal/gpu"
)

func main() {
	file, codeVar, sumVar := "shaders_darwin.go", "metalLibrary", "metalSum"
	if runtime.GOOS == "windows" {
		file, codeVar, sumVar = "shaders_windows.go", "hlslBytecode", "hlslSum"
	}
	name, compiled, code, err := compile()
	if err != nil {
		log.Fatal(err)
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/gen from %s; DO NOT EDIT.\n\n//go:build %s\n\npackage glass\n\n", name, runtime.GOOS)
	fmt.Fprintf(&b, "// %s is the SHA-256 of what %s was compiled from: %s\n// within the renderer's head and tail.\nconst %s = %q\n\n", sumVar, codeVar, name, sumVar, gpu.SourceSum(compiled))
	b.WriteString(gpu.GoBytes(codeVar, code))
	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(file, out, 0o644); err != nil {
		log.Fatal(err)
	}
}
