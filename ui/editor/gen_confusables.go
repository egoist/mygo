//go:build ignore

// Gen writes confusables_gen.go, the characters AmbiguousCharacters
// outlines, from confusables.txt of Unicode's security mechanisms (UTS
// #39): `go generate ./ui/editor`. Its version is pinned, and is to be
// that of Go's unicode package, whose letters, digits and marks the
// editor's words are made of: it stops when they differ. They are the letters, digits and marks it maps to one ASCII
// letter or digit, each a uint32 of the character shifted left 8 bits and
// the ASCII one, in order.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"log"
	"net/http"
	"os"
	"slices"
	"strconv"
	"strings"
	"time"
	"unicode"
)

const (
	version = "17.0.0"
	url     = "https://www.unicode.org/Public/" + version + "/security/confusables.txt"
)

func main() {
	log.SetFlags(0)
	if unicode.Version != version {
		log.Fatalf("Go's unicode package is of Unicode %s: set version to it", unicode.Version)
	}
	client := http.Client{Timeout: time.Minute}
	resp, err := client.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("downloading %s: %s", url, resp.Status)
	}
	var notice []string
	var table []uint32
	lines := bufio.NewScanner(resp.Body)
	for lines.Scan() {
		line := lines.Text()
		if c, ok := strings.CutPrefix(line, "# "); ok && (strings.HasPrefix(c, "©") || strings.HasPrefix(c, "Unicode and") || strings.HasPrefix(c, "For terms")) {
			notice = append(notice, c)
		}
		field := strings.Split(line, ";")
		if len(field) < 3 || strings.HasPrefix(line, "#") {
			continue
		}
		src, target := strings.TrimSpace(field[0]), strings.TrimSpace(field[1])
		if strings.Contains(target, " ") {
			continue // a sequence, as rn of m
		}
		r, err1 := strconv.ParseUint(src, 16, 32)
		a, err2 := strconv.ParseUint(target, 16, 32)
		if err1 != nil || err2 != nil {
			log.Fatalf("%q: %v %v", line, err1, err2)
		}
		c := rune(r)
		if c < 0x80 || !('0' <= a && a <= '9' || 'A' <= a && a <= 'Z' || 'a' <= a && a <= 'z') {
			continue
		}
		// The editor looks only at letters, digits and marks in words.
		if !unicode.IsLetter(c) && !unicode.IsDigit(c) && !unicode.IsMark(c) {
			continue
		}
		table = append(table, uint32(c)<<8|uint32(a))
	}
	if err := lines.Err(); err != nil {
		log.Fatal(err)
	}
	if len(notice) != 3 {
		log.Fatalf("%s: found %d lines of its notice, want 3", url, len(notice))
	}
	slices.Sort(table)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen_confusables.go from %s; DO NOT EDIT.\n//\n", url)
	for _, n := range notice {
		fmt.Fprintf(&b, "// %s\n", n)
	}
	b.WriteString("\npackage editor\n\n")
	fmt.Fprintf(&b, "// confusables are the letters, digits and marks Unicode %s's\n", version)
	b.WriteString("// confusables.txt maps to one ASCII letter or digit: each the character\n")
	b.WriteString("// shifted left 8 bits and the ASCII one, in order.\n")
	b.WriteString("var confusables = [...]uint32{")
	for i, v := range table {
		if i%6 == 0 {
			b.WriteString("\n")
		}
		fmt.Fprintf(&b, "0x%07x, ", v)
	}
	b.WriteString("\n}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("confusables_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}
