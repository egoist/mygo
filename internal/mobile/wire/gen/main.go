// Command gen writes the messages of spec.go for the three sides: Go
// (../msgs.go), Swift (the iOS host's Wire.swift) and Kotlin (the Android
// host's Wire.kt).
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"strings"
	"unicode"
)

// Paths from internal/mobile/wire, where go generate runs.
const (
	goOut     = "msgs.go"
	swiftOut  = "../ios/Sources/MyGoHost/Wire.swift"
	kotlinOut = "../android/mygo/src/main/java/dev/mygo/Wire.kt"
)

func main() {
	out := map[string][]byte{goOut: goSource(), swiftOut: swiftSource(), kotlinOut: kotlinSource()}
	for path, b := range out {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			log.Fatal(err)
		}
		if err := os.WriteFile(path, b, 0o644); err != nil {
			log.Fatal(err)
		}
	}
}

// lower makes a Go name the Swift and Kotlin one: ID → id, URLs → urls,
// SafeTop → safeTop, HTMLText → htmlText, BaseURL → baseURL.
func lower(s string) string {
	r := []rune(s)
	i := 0
	for i < len(r) && unicode.IsUpper(r[i]) {
		i++
	}
	switch {
	case i == len(r) || string(r[i:]) == "s":
		return strings.ToLower(s)
	case i > 1:
		i-- // the last capital starts the next word
	}
	return strings.ToLower(string(r[:i])) + string(r[i:])
}

