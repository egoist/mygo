// formatNode prints one node the way gofmt would.
func formatNode(fset *token.FileSet, n ast.Node, sb *strings.Builder) {
	cfg := printer.Config{Mode: printer.UseSpaces | printer.TabIndent, Tabwidth: 4}
	_ = cfg.Fprint(sb, fset, n)
}

// gen emits one .view file's Go.
type gen struct {
	api               *API
	view              *File
	recvName          string // s *T
	recvType          *types.Named
	pkg               *types.Package
	imports           map[string]string
	preferred         map[string]string
	binding           *binder
	scope             *types.Scope
	loaded            map[string]*types.Package
	localNames        map[string]bool
	receiver, context string
	// forbidden are the names generated locals must not take: the
	// package's own, the receiver's, and the imports' (#1457).
	forbidden map[string]bool
	locals    int
	diags     []Diagnostic
}

func (g *gen) errf(pos Position, format string, args ...any) error {
	g.diags = append(g.diags, Diagnostic{Pos: pos, Path: g.view.Path, Msg: fmt.Sprintf(format, args...)})
	return g.diags[len(g.diags)-1]
}

func (g *gen) recordErr(pos Position, err error) error {
	var d Diagnostic
	if errors.As(err, &d) {
		g.diags = append(g.diags, d)
		return d
	}
	return g.errf(pos, "%v", err)
}

// emit renders the file's Go source, gofmt'd.
type line struct {
	dir  string // the //line directive, "" for none
	code string
}

func (g *gen) emit() (string, error) {
	var ls []line
	ui := g.useImport("github.com/egoist/mygo/ui", "ui")
	ls = append(ls, line{code: "func (" + g.recvName + ") View(" + g.context + " *" + ui + ".Context) {"})
	for _, root := range g.view.Roots {
		el, err := g.element(root, 1)
		if err != nil {
			return "", err
		}
		ls = append(ls, el...)
	}
	ls = append(ls, line{code: "}"})
	var sb strings.Builder
	fmt.Fprintf(&sb, "// Code generated by mygo from %s. DO NOT EDIT.\n\n", g.view.Path)
	pkg := g.pkg.Name()
	var imports []string
	for path, alias := range g.imports {
		if alias != "" && alias != path[strings.LastIndex(path, "/")+1:] {
			imports = append(imports, alias+" "+strconv.Quote(path))
		} else {
			imports = append(imports, strconv.Quote(path))
		}
	}
	sort.Strings(imports)
	if len(imports) == 1 {
		fmt.Fprintf(&sb, "package %s\n\nimport %s\n\n", pkg, imports[0])
	} else if len(imports) > 1 {
		fmt.Fprintf(&sb, "package %s\n\nimport (\n", pkg)
		for _, path := range imports {
			fmt.Fprintf(&sb, "\t%s\n", path)
		}
		sb.WriteString(")\n\n")
	} else {
		fmt.Fprintf(&sb, "package %s\n\n", pkg)
	}
	for _, l := range ls {
		if l.dir != "" {
			sb.WriteString("//line " + l.dir + "\n")
		}
		sb.WriteString(l.code)
		sb.WriteString("\n")
	}
	if len(g.diags) > 0 {
		return "", g.diags[0]
	}
	src := sb.String()
	out, err := gofmtSource(src)
	if err != nil {
		return "", g.errf(Position{1, 1}, "the generated Go does not gofmt: %v", err)
	}
	return out, nil
}

// element emits one element's lines, at the given tab depth.
func (g *gen) element(n *Node, depth int) ([]line, error) {
	tab := strings.Repeat("\t", depth)
	c, ok := g.api.Constructors[n.Tag]
	if !ok {
		return nil, g.errf(n.Pos, "unknown element <%s>: no ui constructor of that name", n.Tag)
	}
	if c.Unsupported != "" {
		return nil, g.errf(n.Pos, "<%s> cannot be built from markup yet: %s", n.Tag, c.Unsupported)
	}
	ctorArgs := map[string]*Attr{}
	var fluent []fluentUse
	var events []eventUse
	var keyAttr *Attr
	seen := map[string]bool{}
	for _, a := range n.Attrs {
		if seen[a.Name] {
			return nil, g.errf(a.Pos, "%s is given twice", a.Name)
		}
		seen[a.Name] = true
		switch {
		case a.Name == "key":
			keyAttr = a
		case strings.HasPrefix(a.Name, "on-"):
			query := strings.TrimPrefix(a.Name, "on-")
			m, ok := g.api.Methods[query]
			if !ok || m.Kind != MethodQuery {
				g.errf(a.Pos, "unknown event %s: Element has no such query method of that name", a.Name)
				continue
			}
			events = append(events, eventUse{attr: a, method: m})
		default:
			if p := c.param(a.Name); p != nil {
				ctorArgs[a.Name] = a
				continue
			}
			m, ok := g.api.Methods[a.Name]
			if !ok {
				g.errf(a.Pos, "unknown attribute %s of <%s>", a.Name, n.Tag)
				continue
			}
			if m.Kind != MethodFluent {
				g.errf(a.Pos, "%s is not an attribute: %s", a.Name, m.Unsupported)
				continue
			}
			if m.Unsupported != "" {
				g.errf(a.Pos, "attribute %s cannot be set from markup: %s", a.Name, m.Unsupported)
				continue
			}
			fluent = append(fluent, fluentUse{attr: a, method: m})
		}
	}
	if len(g.diags) > 0 {
		return nil, g.diags[0]
	}
	// The label conflict (#1457): the element's body supplies the
	// constructor's string parameter, and an attribute of the same name
	// becomes the fluent method, as Button's label and Label.
	stringParam := c.stringParam()
	bodySupplies := n.HasBodyText && stringParam != ""
	if bodySupplies && ctorArgs[stringParam] != nil {
		a := ctorArgs[stringParam]
		m, ok := g.api.Methods[a.Name]
		if !ok || m.Kind != MethodFluent {
			return nil, g.errf(a.Pos, "%s supplies both the text and the %s parameter", a.Name, a.Name)
		}
		fluent = append(fluent, fluentUse{attr: a, method: m})
		delete(ctorArgs, a.Name)
	}
	if n.HasBodyText && n.HasElements {
		return nil, g.errf(n.Pos, "<%s> holds both text and elements: wrap the text in its own element", n.Tag)
	}
	if n.HasBodyText && stringParam == "" {
		return nil, g.errf(n.Pos, "<%s> holds no text: nothing of <%s> takes its body's words; a <text> shows them", n.Tag, n.Tag)
	}
	for _, p := range c.Params {
		if !p.Required {
			continue
		}
		if p.Name == stringParam && bodySupplies {
			continue
		}
		if _, ok := ctorArgs[p.Name]; !ok {
			return nil, g.errf(n.Pos, "<%s> needs a %s: give it as an attribute%s", n.Tag, p.Name, bodyHint(stringParam))
		}
	}
	name := g.local()
	// The body supplies the constructor's string parameter: a literal as
	// it is, mixed text and expressions as a format. The ui's text
	// constructor takes the format itself (Textf), sparing apps that
	// format from linking fmt (#1457).
	var bodyArg string
	var textf string
	if bodySupplies {
		lit, format, fargs, err := g.bodyValue(n)
		if err != nil {
			return nil, err
		}
		if format != "" && c.GoName == "Text" {
			textf = format + "\x00" + fargs
		} else if format != "" {
			bodyArg = g.useImport("fmt", "fmt") + ".Sprintf(" + strconv.Quote(format) + ", " + fargs + ")"
		} else {
			bodyArg = lit
		}
	}
	var args []string
	if textf == "" {
		for _, p := range c.Params {
			if p.Name == stringParam && bodySupplies {
				args = append(args, bodyArg)
				continue
			}
			a := ctorArgs[p.Name]
			if a == nil {
				continue
			}
			if p.Variadic {
				vargs, err := g.variadicArgs(a, p.Type)
				if err != nil {
					return nil, err
				}
				args = append(args, vargs...)
				continue
			}
			arg, err := g.value(a, p.Type, p.Ptr)
			if err != nil {
				return nil, err
			}
			args = append(args, arg)
		}
	}
	contextArg := g.keyCall(n, keyAttr)
	call, err := g.constructorCall(c, contextArg, args, n.Pos)
	if err != nil {
		return nil, err
	}
	if textf != "" {
		format, fargs, _ := strings.Cut(textf, "\x00")
		call = g.useImport("github.com/egoist/mygo/ui", "ui") + ".Textf(" + contextArg + strconv.Quote(format) + ", " + fargs + ")"
	}
	var ls []line
	if len(fluent) == 0 && len(n.Children) == 0 && len(events) == 0 {
		// Nothing more is asked of it.
		ls = append(ls, line{dir: g.dir(n.Pos), code: tab + call})
		return ls, nil
	}
	ls = append(ls, line{dir: g.dir(n.Pos), code: tab + name + " := " + call})
	sort.SliceStable(fluent, func(i, j int) bool {
		return fluent[i].attr.Pos.Line < fluent[j].attr.Pos.Line || fluent[i].attr.Pos.Line == fluent[j].attr.Pos.Line && fluent[i].attr.Pos.Col < fluent[j].attr.Pos.Col
	})
	for _, f := range fluent {
		call, err := g.methodCall(f)
		if err != nil {
			return nil, err
		}
		ls = append(ls, line{dir: g.dir(f.attr.Pos), code: tab + name + call})
	}
	if len(n.Children) > 0 {
		ls = append(ls, line{code: tab + name + ".Children(func() {"})
		for _, ch := range n.Children {
			cls, err := g.element(ch, depth+1)
			if err != nil {
				return nil, err
			}
			ls = append(ls, cls...)
		}
		// The close maps to the element itself, so a panic in it does
		// not land on the last child.
		ls = append(ls, line{dir: g.dir(n.Pos), code: tab + "})"})
	}
	// Each event asks in its own if, never an else: one may bring the
	// next.
	for _, e := range events {
		body, wrap, err := g.handler(e.attr)
		if err != nil {
			return nil, err
		}
		ls = append(ls, line{dir: g.dir(e.attr.Pos), code: tab + "if " + name + "." + e.method.GoName + "() {"})
		inner := tab + "\t"
		if wrap {
			ls = append(ls, line{dir: g.dir(e.attr.Pos), code: inner + "func() {"})
			inner += "\t"
		}
		for _, b := range splitGoLines(body) {
			ls = append(ls, line{dir: g.dir(e.attr.Pos), code: inner + b})
		}
		if wrap {
			ls = append(ls, line{dir: g.dir(e.attr.Pos), code: tab + "\t}()"})
		}
		ls = append(ls, line{dir: g.dir(e.attr.Pos), code: tab + "}"})
	}
	return ls, nil
}

// splitGoLines splits formatted Go statements on line breaks outside raw
// string literals and block comments, so //line directives and indentation
// are never injected inside a backtick string's bytes.
func splitGoLines(src string) []string {
	var lines []string
	start := 0
	for i := 0; i < len(src); {
		switch src[i] {
		case '\n':
			lines = append(lines, src[start:i])
			i++
			start = i
		case '`':
			i++
			for i < len(src) && src[i] != '`' {
				i++
			}
			if i < len(src) {
				i++
			}
		case '"', '\'':
			q := src[i]
			i++
			for i < len(src) && src[i] != q && src[i] != '\n' {
				if src[i] == '\\' && i+1 < len(src) {
					i += 2
					continue
				}
				i++
			}
			if i < len(src) && src[i] == q {
				i++
			}
		case '/':
			if i+1 < len(src) && src[i+1] == '/' {
				for i < len(src) && src[i] != '\n' {
					i++
				}
			} else if i+1 < len(src) && src[i+1] == '*' {
				i += 2
				for i+1 < len(src) && (src[i] != '*' || src[i+1] != '/') {
					i++
				}
				if i+1 < len(src) {
					i += 2
				}
			} else {
				i++
			}
		default:
			i++
		}
	}
	lines = append(lines, src[start:])
	return lines
}

type fluentUse struct {
	attr   *Attr
	method *Method
}

type eventUse struct {
	attr   *Attr
	method *Method
}

func bodyHint(stringParam string) string {
	if stringParam != "" {
		return " or its text"
	}
	return ""
}

// dir is the //line directive for a position in this view.
func (g *gen) dir(p Position) string {
	return fmt.Sprintf("%s:%d:%d", g.view.Path, p.Line, p.Col)
}

// keyCall is the Context with the element's key, or c when none: keys
// are given before construction, never after (#1457).
func (g *gen) keyCall(n *Node, keyAttr *Attr) string {
	if keyAttr == nil {
		return g.context + ".Key(" + strconv.Quote(fmt.Sprintf("%s:%d:%d", g.view.Path, n.Pos.Line, n.Pos.Col)) + "), "
	}
	if len(keyAttr.Value) == 1 && keyAttr.Value[0].IsExpr {
		expr, err := g.rewrite(keyAttr.Value[0])
		if err != nil {
			g.recordErr(keyAttr.Pos, err)
			return g.context + ".Key(nil), "
		}
		return g.context + ".Key(" + expr + "), "
	}
	if len(keyAttr.Value) == 1 && !keyAttr.Value[0].IsExpr {
		return g.context + ".Key(" + strconv.Quote(keyAttr.Value[0].Lit) + "), "
	}
	g.errf(keyAttr.Pos, "a key is one value")
	return g.context + ".Key(nil), "
}

// param finds the constructor parameter an attribute names.
func (c *Constructor) param(name string) *Param {
	for i := range c.Params {
		if c.Params[i].Name == name {
			return &c.Params[i]
		}
	}
	return nil
}

// stringParam is the constructor's parameter its text body supplies: the
// label or s by name, else the first that takes a string.
func (c *Constructor) stringParam() string {
	for _, p := range c.Params {
		if (p.Name == "label" || p.Name == "s") && isStringType(p.Type) {
			return p.Name
		}
	}
	for _, p := range c.Params {
		if isStringType(p.Type) {
			return p.Name
		}
	}
	return ""
}

func isStringType(t types.Type) bool {
	b, ok := t.Underlying().(*types.Basic)
	return ok && b.Kind() == types.String
}

// variadicArgs emits one or more arguments filling a variadic parameter
// of element type elem.
func (g *gen) variadicArgs(a *Attr, elem types.Type) ([]string, error) {
	if a.Bare {
		return nil, nil
	}
	var args []string
	for _, part := range a.Value {
		if part.IsExpr {
			expr, err := g.rewrite(part)
			if err != nil {
				return nil, g.recordErr(a.Pos, err)
			}
			args = append(args, expr)
			continue
		}
		for _, item := range strings.Split(part.Lit, ",") {
			item = strings.TrimSpace(item)
			if item == "" {
				continue
			}
			args = append(args, g.literal(item, elem, a))
		}
	}
	if len(args) == 0 {
		return nil, g.errf(a.Pos, "attribute %s needs a value", a.Name)
	}
	return args, nil
}

// methodCall emits one fluent call with its arguments.
func (g *gen) methodCall(f fluentUse) (string, error) {
	m := f.method
	if f.attr.Bare {
		switch {
		case len(m.Params) == 0, len(m.Params) == 1 && m.Params[0].Variadic:
			return "." + m.GoName + "()", nil
		case len(m.Params) == 1 && isBoolType(m.Params[0].Type):
			return "." + m.GoName + "(true)", nil
		default:
			return "", g.errf(f.attr.Pos, "attribute %s needs a value", f.attr.Name)
		}
	}
	if len(m.Params) == 0 {
		return "", g.errf(f.attr.Pos, "%s takes nothing: write it bare, %s", f.attr.Name, f.attr.Name)
	}
	if len(m.Params) == 1 && !m.Params[0].Variadic {
		arg, err := g.value(f.attr, m.Params[0].Type, m.Params[0].Ptr)
		if err != nil {
			return "", err
		}
		return "." + m.GoName + "(" + arg + ")", nil
	}
	if len(m.Params) == 1 && m.Params[0].Variadic {
		args, err := g.variadicArgs(f.attr, m.Params[0].Type)
		if err != nil {
			return "", err
		}
		return "." + m.GoName + "(" + strings.Join(args, ", ") + ")", nil
	}
	// Multiple parameters (fixed, or fixed with an optional variadic tail):
	// values are comma-separated, except a trailing string parameter,
	// which takes the rest whole, commas and all (#1457).
	required := 0
	for _, p := range m.Params {
		if p.Required {
			required++
		}
	}
	variadic := m.Params[len(m.Params)-1].Variadic
	paramAt := func(i int) *Param {
		if i < len(m.Params) {
			return &m.Params[i]
		}
		if variadic {
			return &m.Params[len(m.Params)-1]
		}
		return nil
	}
	var args []string
	pi := 0
	for idx, part := range f.attr.Value {
		if part.IsExpr {
			expr, err := g.rewrite(part)
			if err != nil {
				return "", g.recordErr(f.attr.Pos, err)
			}
			p := paramAt(pi)
			if p == nil {
				return "", g.errf(part.Pos, "more values than %s takes", f.attr.Name)
			}
			cv, err := g.convert(expr, p, f.attr)
			if err != nil {
				return "", err
			}
			args = append(args, cv)
			pi++
			continue
		}
		rest := part.Lit
		if idx > 0 {
			// A comma after an {expr} separates it from what follows.
			trimmed := strings.TrimLeft(rest, " \t")
			if strings.HasPrefix(trimmed, ",") {
				rest = strings.TrimLeft(trimmed[1:], " \t")
			}
		}
		for rest != "" {
			p := paramAt(pi)
			if p != nil && pi == len(m.Params)-1 && !p.Variadic && isStringType(p.Type) {
				args = append(args, g.literal(rest, p.Type, f.attr))
				pi++
				break
			}
			head, tail, hasComma := strings.Cut(rest, ",")
			if hasComma {
				rest = strings.TrimLeft(tail, " \t")
			} else {
				rest = ""
			}
			item := strings.TrimSpace(head)
			if item == "" {
				continue
			}
			if p == nil {
				return "", g.errf(part.Pos, "more values than %s takes", f.attr.Name)
			}
			args = append(args, g.literal(item, p.Type, f.attr))
			pi++
		}
	}
	if !variadic && pi != len(m.Params) {
		return "", g.errf(f.attr.Pos, "%s takes %d values, got %d", f.attr.Name, len(m.Params), pi)
	}
	if variadic && pi < required {
		return "", g.errf(f.attr.Pos, "%s takes at least %d values, got %d", f.attr.Name, required, pi)
	}
	return "." + m.GoName + "(" + strings.Join(args, ", ") + ")", nil
}

// handler emits an event handler's body: a receiver method name, or Go
// statements in braces. wrap reports whether the body uses return, defer
// or labels and needs a closure of its own.
func (g *gen) handler(a *Attr) (string, bool, error) {
	b := g.binding
	if len(a.Value) == 1 && !a.Value[0].IsExpr {
		name := a.Value[0].Lit
		if !validIdent(name) {
			return "", false, g.errf(a.Pos, "on-... names a method of the receiver: %q is not a name", name)
		}
		if b.members[name] == nil {
			return "", false, g.errf(a.Pos, "%s is not a method of %s", name, g.recvType.Obj().Name())
		}
		return g.receiver + "." + name + "()", false, nil
	}
	if len(a.Value) == 1 && a.Value[0].IsExpr {
		src, wrap, err := b.body(a.Value[0].Expr, a.Value[0].Pos, g.view.Path)
		if err != nil {
			return "", false, g.recordErr(a.Value[0].Pos, err)
		}
		return src, wrap, nil
	}
	return "", false, g.errf(a.Pos, "an event takes one handler")
}

// value emits one single-argument attribute value.
func (g *gen) value(a *Attr, t types.Type, ptr bool) (string, error) {
	if a.Bare {
		return "", g.errf(a.Pos, "attribute %s needs a value", a.Name)
	}
	if len(a.Value) == 1 && a.Value[0].IsExpr {
		expr, err := g.rewrite(a.Value[0])
		if err != nil {
			return "", g.recordErr(a.Pos, err)
		}
		return g.convert(expr, &Param{Type: t, Ptr: ptr, Required: true}, a)
	}
	if len(a.Value) == 1 && !a.Value[0].IsExpr {
		lit := a.Value[0].Lit
		if ptr {
			// Bindings take addresses, not literals.
			return "", g.errf(a.Pos, "a pointer parameter needs a Go expression, as {%s: \"...\"}", "field")
		}
		if isStringType(t) {
			return strconv.Quote(lit), nil
		}
		return g.literal(lit, t, a), nil
	}
	// A single argument is one value, not a format.
	return "", g.errf(a.Pos, "attribute %s takes one value: write the parts as a Go expression", a.Name)
}

// rewrite binds one expression part to the generated method's names,
// and notes the packages it names, so the generated file imports them.
func (g *gen) rewrite(p TextPart) (string, error) {
	src, _, err := g.binding.expr(p.Expr, p.Pos, g.view.Path)
	if err != nil {
		return "", err
	}
	return src, nil
}

// useImport assigns one alias per package.
func (g *gen) useImport(path, preferred string) string {
	if name, ok := g.imports[path]; ok {
		return name
	}
	available := func(name string) bool {
		if g.localNames[name] || g.pkg.Scope().Lookup(name) != nil {
			return false
		}
		if obj := g.scope.Lookup(name); obj != nil {
			p, ok := obj.(*types.PkgName)
			return ok && p.Imported().Path() == path
		}
		return true
	}
	base := preferred
	if alias := g.preferred[path]; alias != "" {
		base = alias
	}
	name := base
	if !available(name) && base != preferred && available(preferred) {
		name = preferred
	}
	for i := 1; !available(name); i++ {
		name = preferred + strconv.Itoa(i)
	}
	g.imports[path] = name
	g.forbidden[name] = true
	if g.scope.Lookup(name) == nil {
		g.scope.Insert(types.NewPkgName(token.NoPos, g.pkg, name, g.loaded[path]))
	}
	return name
}

// convert preserves compatible pointers and addresses compatible values.
func (g *gen) convert(expr string, p *Param, a *Attr) (string, error) {
	if !p.Ptr {
		return expr, nil
	}
	tv, err := g.binding.eval(expr)
	if err != nil {
		return "", g.errf(a.Pos, "%v", err)
	}
	if types.AssignableTo(tv.Type, p.Type) {
		return expr, nil
	}
	if ptr, ok := p.Type.(*types.Pointer); ok {
		// Defer generic inference to the complete constructor call.
		if _, generic := ptr.Elem().(*types.TypeParam); generic {
			return expr, nil
		}
		if tv.Addressable() && types.AssignableTo(types.NewPointer(tv.Type), p.Type) {
			return "&" + expr, nil
		}
	}
	return "", g.errf(a.Pos, "binding needs %s or an addressable value of its element type", types.TypeString(p.Type, nil))
}

func (g *gen) constructorCall(c *Constructor, contextArg string, args []string, pos Position) (string, error) {
	makeCall := func() string {
		return g.useImport("github.com/egoist/mygo/ui", "ui") + "." + c.GoName + "(" + contextArg + strings.Join(args, ", ") + ")"
	}
	call := makeCall()
	if len(c.TypeParams) == 0 {
		return call, nil
	}
	_, original := g.binding.eval(call)
	if original == nil {
		return call, nil
	}
	var choices []int
	for i, p := range c.Params {
		if i >= len(args) || !p.Ptr {
			continue
		}
		if tv, err := g.binding.eval(args[i]); err == nil && tv.Addressable() {
			choices = append(choices, i)
		}
	}
	var adapt func(int) bool
	adapt = func(at int) bool {
		if at == len(choices) {
			_, err := g.binding.eval(makeCall())
			return err == nil
		}
		if adapt(at + 1) {
			return true
		}
		i := choices[at]
		old := args[i]
		args[i] = "&" + old
		if adapt(at + 1) {
			return true
		}
		args[i] = old
		return false
	}
	if adapt(0) {
		return makeCall(), nil
	}
	return "", g.errf(pos, "%v", original)
}

// bodyValue is the element's text as its constructor's string argument:
// the literal as it is, mixed text and expressions as a format with its
// arguments, its literal % escaped (#1457). For the ui's text
// constructors the format and arguments go to Textf themselves; textf
// tells them apart, saving apps that format from linking fmt.
func (g *gen) bodyValue(n *Node) (literal string, textf string, args string, err error) {
	hasExpr := false
	for _, part := range n.Text {
		if part.IsExpr {
			hasExpr = true
			break
		}
	}
	if !hasExpr {
		var lit strings.Builder
		for _, part := range n.Text {
			lit.WriteString(part.Lit)
		}
		return strconv.Quote(lit.String()), "", "", nil
	}
	var parts []string
	var f string
	for _, part := range n.Text {
		if part.IsExpr {
			expr, e := g.rewrite(part)
			if e != nil {
				return "", "", "", g.recordErr(part.Pos, e)
			}
			f += "%v"
			parts = append(parts, expr)
			continue
		}
		f += strings.ReplaceAll(part.Lit, "%", "%%")
	}
	args = strings.Join(parts, ", ")
	return "", f, args, nil
}

// literal converts a literal string to the type t: an enum's constant
// by name, or the basic kinds.
func (g *gen) literal(lit string, t types.Type, a *Attr) string {
	t = types.Unalias(t)
	if _, ok := t.(*types.TypeParam); ok {
		// A generic parameter infers its type from the call: the literal
		// stands as it is written, a string quoted, a number plain.
		if _, err := strconv.ParseFloat(lit, 64); err == nil {
			return lit
		}
		if lit == "true" || lit == "false" {
			return lit
		}
		return strconv.Quote(lit)
	}
	if _, ok := t.(*types.Named); ok {
		// An enum constant of the ui package: center -> ui.Center.
		if name, ok := g.api.constantOf(lit, t); ok {
			return g.useImport("github.com/egoist/mygo/ui", "ui") + "." + name
		}
		g.errf(a.Pos, "%q does not read as a %s", lit, types.TypeString(t, nil))
		return "nil"
	}
	b, ok := t.Underlying().(*types.Basic)
	if !ok {
		g.errf(a.Pos, "%q does not read as a %s", lit, types.TypeString(t, nil))
		return "nil"
	}
	switch b.Kind() {
	case types.String:
		return strconv.Quote(lit)
	case types.Bool:
		if lit == "true" || lit == "false" {
			return lit
		}
	case types.Int, types.Int8, types.Int16, types.Int32, types.Int64, types.UntypedInt:
		if _, err := strconv.ParseInt(lit, 0, 64); err == nil {
			return lit
		}
	case types.Uint, types.Uint8, types.Uint16, types.Uint32, types.Uint64, types.Uintptr:
		if _, err := strconv.ParseUint(lit, 0, 64); err == nil {
			return lit
		}
	case types.Float32, types.Float64, types.UntypedFloat:
		if _, err := strconv.ParseFloat(lit, 64); err == nil {
			return lit
		}
	}
	g.errf(a.Pos, "%q does not read as a %s", lit, types.TypeString(t, nil))
	return "nil"
}

// local is the name of the next generated local: one the app itself
// does not name, so nothing of the app's is captured by it (#1457).
func (g *gen) local() string {
	for {
		g.locals++
		name := "el" + strconv.Itoa(g.locals)
		if !g.forbidden[name] {
			return name
		}
	}
}

func isBoolType(t types.Type) bool {
	b, ok := t.Underlying().(*types.Basic)
	return ok && b.Kind() == types.Bool
}

func validIdent(s string) bool {
	return token.IsIdentifier(s)
}

// gofmtSource formats generated Go.
func gofmtSource(src string) (string, error) {
	out, err := format.Source([]byte(src))
	if err != nil {
		return "", err
	}
	return string(out), nil
}
