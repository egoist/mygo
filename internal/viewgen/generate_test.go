// TestGenerateCleanBootstrap is the round's anchor (#1457): the app's
// main already calls s.View, no *_view.go exists, and Generate writes
// one that the package type-checks with. Nothing builds the app first.
func TestGenerateCleanBootstrap(t *testing.T) {
	dir := writeApp(t, map[string]string{
		"counter.go":   counterGo,
		"counter.view": counterView,
		"main.go":      counterMain,
	})
	written, err := Generate(dir)
	if err != nil {
		t.Fatal(err)
	}
	if len(written) != 1 || filepath.Base(written[0]) != "counter_view.go" {
		t.Fatalf("written: %v", written)
	}
	src, err := os.ReadFile(filepath.Join(dir, "counter_view.go"))
	if err != nil {
		t.Fatal(err)
	}
	generated := string(src)
	for _, want := range []string{
		"func (s *counter) View(c *ui.Context) {",
		"// Code generated by mygo from counter.view. DO NOT EDIT.",
		`c.Key("counter.view:2:1")`,
		"ui.Column(", ".Fill()", ".Center()", ".Gap(16)",
		"FontSize(56)",
		"s.n",
		"if el", ".Clicked()",
		"s.Decrement()",
		"s.Increment()",
		".Disabled(s.n == 0)",
		`"↑ and ↓ count too"`,
	} {
		if !strings.Contains(generated, want) {
			t.Errorf("generated Go misses %q:\n%s", want, generated)
		}
	}
	// The label conflict: the body supplies the constructor's label, the
	// attribute names the accessible Label.
	if !strings.Contains(generated, `.Label("Decrement")`) {
		t.Errorf("no .Label(\"Decrement\"):\n%s", generated)
	}
	if strings.Count(generated, `"−"`) != 1 {
		t.Errorf("the body text − appears once:\n%s", generated)
	}
	// What the app's own Go does not use stays out.
	if strings.Contains(generated, "fmt.") && !strings.Contains(generated, "Sprintf") {
		t.Errorf("fmt imported without a use:\n%s", generated)
	}
	// Type-check the whole app package with the generated file: the
	// verify pass already did, but prove it on disk.
	checkDir := t.TempDir()
	if err := os.CopyFS(checkDir, os.DirFS(dir)); err != nil {
		t.Fatal(err)
	}
	out := mustRun(t, checkDir, "go", "build", "./...")
	if out != "" {
		t.Fatalf("go build with the generated file: %s", out)
	}
}

// TestGenerateIdempotent does not rewrite what did not change.
func TestGenerateIdempotent(t *testing.T) {
	dir := writeApp(t, map[string]string{
		"counter.go":   counterGo,
		"counter.view": counterView,
		"main.go":      counterMain,
	})
	if _, err := Generate(dir); err != nil {
		t.Fatal(err)
	}
	written, err := Generate(dir)
	if err != nil {
		t.Fatal(err)
	}
	if len(written) != 0 {
		t.Fatalf("second Generate rewrote %v", written)
	}
}

// TestGenerateErrorsPointAtTheView checks the diagnostics markup
// writers see: unknown tags and attributes, missing arguments, unknown
// handlers, at their places.
func TestGenerateErrorsPointAtTheView(t *testing.T) {
	dir := writeApp(t, map[string]string{
		"counter.go": counterGo,
		"counter.view": `<view type="counter">
<colunm fill>
	<bottun>Hi</bottun>
	<text font-size="bad" unknown-attr="1">x</text>
	<button on-clicked="NoSuchMethod">Go</button>
</colunm>
</view>
`,
		"main.go": counterMain,
	})
	_, err := Generate(dir)
	if err == nil {
		t.Fatal("no error")
	}
	msg := err.Error()
	for _, want := range []string{
		"counter.view:2:1", "unknown element <colunm>",
	} {
		if !strings.Contains(msg, want) {
			t.Errorf("error %q misses %q", msg, want)
		}
	}
	// Nothing was written for a broken view.
	if _, statErr := os.Stat(filepath.Join(dir, "counter_view.go")); statErr == nil {
		t.Fatal("a broken view wrote its output")
	}
}

// mustRun runs a command in dir and returns what it printed, failing
// the test on error.
func mustRun(t *testing.T, dir string, name string, args ...string) string {
	t.Helper()
	cmd := exec.Command(name, args...)
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	if err != nil {
		return string(out)
	}
	return ""
}

// TestGenerateBindings is the markup of a form: pointer bindings, enum
// attributes, multi-value and bare attributes, text with a literal %
// and expressions.
func TestGenerateBindings(t *testing.T) {
	dir := writeApp(t, map[string]string{
		"form.go": `package main

import "fmt"

type editor struct {
	Name  string
	Count int
	Note  *string
}

func (s *editor) Clear() { s.Name = "" }

func (s *editor) Label() string { return fmt.Sprint(s.Count) }
`,
		"form.view": `<view type="editor">
<column padding="4,8" gap="4">
	<text-input value="{Name}" on-changed={s.Clear()}></text-input>
	<text>100% complete: {Name}</text>
	<text text-align="center">{Count} done</text>
	<text bold>{fmt.Sprintf("%s!", Name)}</text>
</column>
</view>
`,
		"main.go": `package main

import "github.com/egoist/mygo/ui"

func main() { _ = ui.View((&editor{}).View) }
`})
	if _, err := Generate(dir); err != nil {
		t.Fatal(err)
	}
	src, err := os.ReadFile(filepath.Join(dir, "form_view.go"))
	if err != nil {
		t.Fatal(err)
	}
	g := string(src)
	for _, want := range []string{
		"&s.Name",        // pointer binding
		".Padding(4, 8)", // multi-value
		`ui.Textf(c.Key("form.view:4:2"), "100%% complete: %v", s.Name)`, // Textf: % escaped, %v for the expr
		"ui.Center",                  // enum
		".Bold()",                    // bare attribute
		`fmt.Sprintf("%s!", s.Name)`, // a Go call with a package qualifier
		"s.Clear()",                  // handler block
	} {
		if !strings.Contains(g, want) {
			t.Errorf("generated misses %q:\n%s", want, g)
		}
	}
}

