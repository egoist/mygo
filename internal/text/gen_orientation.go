//go:build ignore

// Gen writes orientation_table.go, the characters that stand upright in
// vertical text, from Unicode's Vertical_Orientation property (UAX #50):
// `go generate ./internal/text`. It keeps the ranges of U, Tu and Tr;
// the others, R, turn sideways.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"slices"
	"strconv"
	"strings"
)

const source = "https://www.unicode.org/Public/16.0.0/ucd/VerticalOrientation.txt"

func main() {
	log.SetFlags(0)
	resp, err := http.Get(source)
	if err != nil {
		log.Fatal(err)
	}
	data, err := io.ReadAll(resp.Body)
	resp.Body.Close()
	if err != nil || resp.StatusCode != http.StatusOK {
		log.Fatalf("downloading %s: %v %s", source, err, resp.Status)
	}
	type span struct {
		lo, hi rune
		vo     string
	}
	var spans []span
	lines := bufio.NewScanner(bytes.NewReader(data))
	for lines.Scan() {
		line, _, _ := strings.Cut(lines.Text(), "#")
		cps, vo, ok := strings.Cut(line, ";")
		if !ok {
			continue
		}
		vo = strings.TrimSpace(vo)
		lo, hi, ok := strings.Cut(strings.TrimSpace(cps), "..")
		if !ok {
			hi = lo
		}
		a, err1 := strconv.ParseUint(lo, 16, 32)
		b, err2 := strconv.ParseUint(hi, 16, 32)
		if err1 != nil || err2 != nil {
			log.Fatalf("bad line %q", lines.Text())
		}
		if vo != "R" {
			spans = append(spans, span{rune(a), rune(b), vo})
		}
	}
	if err := lines.Err(); err != nil {
		log.Fatal(err)
	}
	slices.SortFunc(spans, func(a, b span) int { return int(a.lo - b.lo) })
	var merged []span
	for _, s := range spans {
		if n := len(merged); n > 0 && merged[n-1].vo == s.vo && merged[n-1].hi+1 == s.lo {
			merged[n-1].hi = s.hi
			continue
		}
		merged = append(merged, s)
	}
	names := map[string]string{"U": "voU", "Tu": "voTu", "Tr": "voTr"}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen_orientation.go from %s; DO NOT EDIT.\n\npackage text\n\n", source)
	b.WriteString("// orientations are the ranges of characters whose Vertical_Orientation\n// is not R, in order.\nvar orientations = [...]orientationRange{\n")
	for _, s := range merged {
		fmt.Fprintf(&b, "\t{0x%04X, 0x%04X, %s},\n", s.lo, s.hi, names[s.vo])
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("orientation_table.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
}
