// Command gen writes capi_gen.go, the Go mirrors of the structures of
// CEF's C API that package cef uses, from the include directory of a CEF
// binary distribution. Run it from internal/cef:
//
//	go run ./gen <cef_binary_…>/include
//
// The headers of a distribution describe the newest API version it
// supports (cef_api_versions.h), with removed members kept as placeholders
// and experimental ones guarded; members guarded by CEF_API_ADDED,
// CEF_API_REMOVED and CEF_API_RANGE are kept as apiVersion has them. A
// structure is a list of pointer-sized function slots after its base, or
// plain fields, so the Go types share the C layout on 64-bit Linux.
