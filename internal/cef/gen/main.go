type field struct {
	name  string // the C name
	typ   string // the C type, or "" for a function slot
	array string // the length of an array, else ""
}

type structure struct {
	name   string
	fields []field
}

var (
	structs  = map[string]*structure{}
	enums    = map[string]bool{}
	typedefs = map[string]string{}
	// enumBodies holds the text between the braces of each enumeration.
	enumBodies = map[string]string{}
)

func main() {
	if len(os.Args) != 2 {
		log.Fatal("usage: go run ./gen <cef include directory>")
	}
	include := os.Args[1]
	var files []string
	for _, dir := range []string{"capi", "internal"} {
		matches, err := filepath.Glob(filepath.Join(include, dir, "*.h"))
		if err != nil {
			log.Fatal(err)
		}
		files = append(files, matches...)
	}
	for _, f := range files {
		data, err := os.ReadFile(f)
		if err != nil {
			log.Fatal(err)
		}
		parse(preprocess(stripComments(string(data))))
	}
	version, hash := versionInfo(include)

	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by internal/cef/gen from the headers of CEF %s; DO NOT EDIT.\n\n", version)
	out.WriteString("//go:build linux && (amd64 || arm64)\n\npackage cef\n\n")
	fmt.Fprintf(&out, "// The CEF version the structures come from, the API version they follow\n// and the hash libcef reports for it on Linux (cef_api_hash).\nconst (\n\tcefVersion = %q\n\tapiVersion = %d\n\tapiHash    = %q\n)\n", version, apiVersion, hash)

	// capi_gen_test.go lists the structures with their C names, for
	// TestLayout, which checks the Go layouts against the headers.
	var table bytes.Buffer
	table.WriteString("// Code generated by internal/cef/gen; DO NOT EDIT.\n\n//go:build linux && (amd64 || arm64)\n\npackage cef\n\nvar generatedLayouts = []layout{\n")

	done := map[string]bool{}
	var emit func(name string)
	emit = func(name string) {
		if done[name] {
			return
		}
		done[name] = true
		s := structs[name]
		if s == nil {
			log.Fatalf("no structure %s", name)
		}
		fmt.Fprintf(&table, "\t{%q, %s{}, []string{", name, goName(name, true))
		for i, f := range s.fields {
			if i > 0 {
				table.WriteString(", ")
			}
			fmt.Fprintf(&table, "%q", f.name)
		}
		table.WriteString("}},\n")
		var body bytes.Buffer
		var deps []string
		for _, f := range s.fields {
			typ := "uintptr" // a function slot
			if f.typ != "" {
				var dep string
				typ, dep = goType(f.typ)
				if dep != "" {
					deps = append(deps, dep)
				}
			}
			if f.array != "" {
				typ = "[" + f.array + "]" + typ
			}
			fmt.Fprintf(&body, "\t%s %s\n", goName(f.name, false), typ)
		}
		fmt.Fprintf(&out, "\n// %s is %s.\ntype %s struct {\n%s}\n", goName(name, true), name, goName(name, true), body.String())
		for _, d := range deps {
			emit(d)
		}
	}
	for _, r := range roots {
		emit(r)
	}
	for _, e := range constants {
		body, ok := enumBodies[e]
		if !ok {
			log.Fatalf("no enumeration %s", e)
		}
		fmt.Fprintf(&out, "\n// %s\nconst (\n", e)
		prev := ""
		for _, item := range strings.Split(body, ",") {
			item = strings.Join(strings.Fields(item), " ")
			if item == "" {
				continue
			}
			name, value, explicit := strings.Cut(item, "=")
			name = strings.TrimSpace(name)
			value = strings.TrimSpace(value)
			switch {
			case explicit:
				value = strings.ReplaceAll(value, "UINT_MAX", "0xFFFFFFFF")
				// Values name earlier constants of the enumeration.
				for _, w := range regexp.MustCompile(`[A-Z][A-Z0-9_]+`).FindAllString(value, -1) {
					value = strings.Replace(value, w, goName(strings.ToLower(w), false), 1)
				}
			case prev == "":
				value = "0"
			default:
				value = prev + " + 1"
			}
			prev = goName(strings.ToLower(name), false)
			fmt.Fprintf(&out, "\t%s = %s\n", prev, value)
		}
		out.WriteString(")\n")
	}
	src, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatalf("formatting: %v\n%s", err, out.Bytes())
	}
	if err := os.WriteFile("capi_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
	table.WriteString("}\n")
	if src, err = format.Source(table.Bytes()); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("capi_gen_test.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

var (
	lineComment  = regexp.MustCompile(`//[^\n]*`)
	blockComment = regexp.MustCompile(`(?s)/\*.*?\*/`)
)

func stripComments(s string) string {
	return lineComment.ReplaceAllString(blockComment.ReplaceAllString(s, ""), "")
}

// preprocess keeps the lines that apiVersion on 64-bit Linux compiles:
// conditions on the API version and the platform are evaluated, others
// (include guards, C++) are taken as their usual outcome.
func preprocess(s string) string {
	type level struct{ taking, taken, parent bool }
	var stack []level
	taking := true
	var out strings.Builder
	for _, line := range strings.Split(s, "\n") {
		t := strings.TrimSpace(line)
		directive, rest, _ := strings.Cut(strings.TrimPrefix(t, "#"), " ")
		rest = strings.TrimSpace(rest)
		if !strings.HasPrefix(t, "#") {
			if taking {
				out.WriteString(line)
				out.WriteByte('\n')
			}
			continue
		}
		switch directive {
		case "if", "ifdef", "ifndef":
			var v bool
			switch directive {
			case "if":
				v = condition(rest)
			case "ifdef":
				v = defined(rest)
			case "ifndef":
				v = true // include guards
			}
			stack = append(stack, level{taking: v, taken: v, parent: taking})
			taking = taking && v
		case "elif":
			l := &stack[len(stack)-1]
			v := !l.taken && condition(rest)
			l.taking, l.taken = v, l.taken || v
			taking = l.parent && v
		case "else":
			l := &stack[len(stack)-1]
			l.taking, l.taken = !l.taken, true
			taking = l.parent && l.taking
		case "endif":
			l := stack[len(stack)-1]
			stack = stack[:len(stack)-1]
			taking = l.parent
		}
	}
	return out.String()
}

var apiCall = regexp.MustCompile(`^CEF_API_(ADDED|REMOVED|RANGE)\(([^)]*)\)$`)

func condition(c string) bool {
	c = strings.TrimSpace(c)
	if m := apiCall.FindStringSubmatch(c); m != nil {
		args := strings.Split(m[2], ",")
		n := func(i int) int {
			a := strings.TrimSpace(args[i])
			if a == "CEF_EXPERIMENTAL" || a == "CEF_NEXT" {
				return 1 << 30
			}
			v, err := strconv.Atoi(a)
			if err != nil {
				log.Fatalf("API version %q", a)
			}
			return v
		}
		switch m[1] {
		case "ADDED":
			return apiVersion >= n(0)
		case "REMOVED":
			return apiVersion < n(0)
		default:
			return apiVersion >= n(0) && apiVersion < n(1)
		}
	}
	if strings.HasPrefix(c, "defined(") && strings.HasSuffix(c, ")") && !strings.ContainsAny(c[8:len(c)-1], "()|&!") {
		return defined(c[8 : len(c)-1])
	}
	if strings.HasPrefix(c, "!defined(") && strings.HasSuffix(c, ")") && !strings.ContainsAny(c[9:len(c)-1], "()|&!") {
		return !defined(c[9 : len(c)-1])
	}
	switch c {
	case "defined(OS_WIN)", "defined(OS_MAC)", "defined(OS_WIN) || defined(OS_MAC)":
		return false
	case "defined(OS_LINUX)", "defined(OS_POSIX)", "defined(CEF_X11)":
		return true
	}
	return false
}

func defined(name string) bool {
	switch strings.TrimSpace(name) {
	case "OS_LINUX", "OS_POSIX", "CEF_X11", "CEF_STRING_TYPE_UTF16", "ARCH_CPU_64_BITS":
		return true
	}
	return false
}

var (
	structStart = regexp.MustCompile(`typedef\s+struct\s+_(\w+)\s*\{`)
	enumStart   = regexp.MustCompile(`typedef\s+enum\s*(?:\w+\s*)?\{`)
	simpleDef   = regexp.MustCompile(`(?m)^\s*typedef\s+([\w\s\*]+?)\s*\b(\w+)\s*;`)
	funcSlot    = regexp.MustCompile(`\(\s*(?:CEF_CALLBACK\s*)?\*\s*(\w+)\s*\)\s*\(`)
	plainField  = regexp.MustCompile(`^(.*?)\b(\w+)\s*(?:\[\s*(\w+)\s*\])?$`)
)

func parse(src string) {
	for _, m := range simpleDef.FindAllStringSubmatch(src, -1) {
		if !strings.Contains(m[1], "struct") && !strings.Contains(m[1], "enum") {
			typedefs[m[2]] = strings.Join(strings.Fields(m[1]), " ")
		} else if strings.HasPrefix(strings.TrimSpace(m[1]), "struct") {
			typedefs[m[2]] = strings.Join(strings.Fields(m[1]), " ")
		}
	}
	for _, loc := range enumStart.FindAllStringIndex(src, -1) {
		end := matchBrace(src, loc[1]-1)
		name := strings.Trim(strings.TrimSpace(src[end+1:]), " ")
		name, _, _ = strings.Cut(name, ";")
		name = strings.TrimSpace(name)
		enums[name] = true
		enumBodies[name] = src[loc[1]:end]
	}
	for _, loc := range structStart.FindAllStringSubmatchIndex(src, -1) {
		open := loc[1] - 1
		end := matchBrace(src, open)
		tail, _, _ := strings.Cut(src[end+1:], ";")
		name := strings.TrimSpace(tail)
		s := &structure{name: name}
		for _, m := range splitMembers(src[open+1 : end]) {
			m = strings.Join(strings.Fields(m), " ")
			if m == "" {
				continue
			}
			if f := funcSlot.FindStringSubmatch(m); f != nil {
				s.fields = append(s.fields, field{name: f[1]})
				continue
			}
			f := plainField.FindStringSubmatch(m)
			if f == nil || strings.TrimSpace(f[1]) == "" {
				log.Fatalf("%s: cannot read member %q", name, m)
			}
			s.fields = append(s.fields, field{name: f[2], typ: strings.TrimSpace(f[1]), array: f[3]})
		}
		structs[name] = s
	}
}

// matchBrace returns the index of the brace closing the one at open.
func matchBrace(s string, open int) int {
	depth := 0
	for i := open; i < len(s); i++ {
		switch s[i] {
		case '{':
			depth++
		case '}':
			depth--
			if depth == 0 {
				return i
			}
		}
	}
	log.Fatal("unbalanced braces")
	return 0
}

// splitMembers splits a structure body at the semicolons outside
// parentheses.
func splitMembers(body string) []string {
	var out []string
	depth, start := 0, 0
	for i, c := range body {
		switch c {
		case '(':
			depth++
		case ')':
			depth--
		case ';':
			if depth == 0 {
				out = append(out, body[start:i])
				start = i + 1
			}
		}
	}
	return out
}

// goType returns the Go type of a C type, and the structure it names when
// it holds one by value.
func goType(c string) (string, string) {
	c = strings.TrimSpace(strings.ReplaceAll(" "+c+" ", " const ", " "))
	if strings.HasSuffix(c, "*") {
		return "uintptr", ""
	}
	c = strings.TrimSpace(strings.TrimPrefix(c, "struct "))
	c = strings.TrimPrefix(c, "_")
	switch c {
	case "size_t", "uintptr_t", "unsigned long", "long unsigned int":
		return "uintptr", ""
	case "int", "int32_t", "signed int":
		return "int32", ""
	case "unsigned int", "uint32_t", "unsigned":
		return "uint32", ""
	case "int64_t", "long", "long long":
		return "int64", ""
	case "uint64_t", "unsigned long long":
		return "uint64", ""
	case "int16_t", "short":
		return "int16", ""
	case "uint16_t", "unsigned short", "char16_t", "uint_least16_t":
		return "uint16", ""
	case "char", "int8_t", "signed char":
		return "int8", ""
	case "unsigned char", "uint8_t":
		return "uint8", ""
	case "double":
		return "float64", ""
	case "float":
		return "float32", ""
	case "cef_string_t":
		return goType("cef_string_utf16_t")
	}
	if enums[c] {
		return "int32", ""
	}
	if _, ok := structs[c]; ok {
		return goName(c, true), c
	}
	if alias, ok := typedefs[c]; ok && alias != c {
		return goType(alias)
	}
	log.Fatalf("unknown C type %q", c)
	return "", ""
}

var keywords = []string{"break", "case", "chan", "const", "continue", "default", "defer", "else", "fallthrough", "for", "func", "go", "goto", "if", "import", "interface", "map", "package", "range", "return", "select", "struct", "switch", "type", "var"}

// goName turns cef_browser_host_t into cefBrowserHost and get_main_frame
// into getMainFrame.
func goName(c string, typ bool) string {
	if typ {
		c = strings.TrimSuffix(c, "_t")
	}
	parts := strings.Split(c, "_")
	var b strings.Builder
	for i, p := range parts {
		if p == "" {
			continue
		}
		if i > 0 && b.Len() > 0 {
			p = strings.ToUpper(p[:1]) + p[1:]
		}
		b.WriteString(p)
	}
	name := b.String()
	if slices.Contains(keywords, name) {
		name += "_"
	}
	return name
}

var (
	versionDef = regexp.MustCompile(`#define CEF_VERSION "([^"]+)"`)
	hashDef    = regexp.MustCompile(`(?s)#define CEF_API_VERSION_` + strconv.Itoa(apiVersion) + ` .*?#elif defined\(OS_LINUX\)\s*#define CEF_API_HASH_\d+ "(\w+)"`)
)

// versionInfo returns the CEF version of the distribution and the hash of
// apiVersion on Linux.
func versionInfo(include string) (string, string) {
	v, err := os.ReadFile(filepath.Join(include, "cef_version.h"))
	if err != nil {
		log.Fatal(err)
	}
	h, err := os.ReadFile(filepath.Join(include, "cef_api_versions.h"))
	if err != nil {
		log.Fatal(err)
	}
	vm, hm := versionDef.FindSubmatch(v), hashDef.FindSubmatch(h)
	if vm == nil || hm == nil {
		log.Fatal("cannot find the CEF version or the hash of the API version")
	}
	return string(vm[1]), string(hm[1])
}
